const PROFILE_SLUGS = new Set(PROFILES.map((p) => p.slug));

// Some "alternatives" entries use an abbreviation, a name with a suffix word
// (Circle/Road/nodes) that isn't part of the actual slug, or refer to a
// place that has no dedicated profile at all — none of these resolve
// correctly through the generic slugify heuristic below.
const LOCATION_ALIASES: Record<string, string> = {
  "vaishno devi circle": "vaishno-devi",
  "sp ring road": "sp-ring-road",
  "sp ring road nodes": "sp-ring-road",
  "cg road": "cg-road",
  nehrunagar: "nehru-nagar",
  sbr: "sindhu-bhavan",
};

function resolveAlternativeSlug(item: string): string | null {
  const name = item.split(" for ")[0].trim().toLowerCase();
  const aliased = LOCATION_ALIASES[name];
  if (aliased) return aliased;

  const heuristic = name
    .replaceAll("–", "-")
    .replaceAll(" ", "-")
    .replace(/-road$/, "")
    .replace(/-+$/, "");
  if (PROFILE_SLUGS.has(heuristic)) return heuristic;

  // No dedicated profile exists for this alternative (e.g. it's mentioned
  // in prose but doesn't have its own page) — drop it rather than link
  // to a non-existent slug.
  return null;
}

/**
 * Meta description for a locality page: leads with the area name and what is
 * actually on offer there (unique per page), within the 155 characters Google
 * shows. Replaces a template that ended mid-sentence ("Compare formats,
 * indicative...") on most pages.
 */
function localityDescription(profile: LocationProfile): string {
  const tail = " Area guide with indicative pricing, access and buyer fit.";
  const head = `${profile.label}, Ahmedabad: `;
  let formats = profile.formats.replace(/\.$/, "");
  const room = 155 - head.length - tail.length - 1;
  if (formats.length > room) {
    const cut = formats.slice(0, room);
    const at = Math.max(cut.lastIndexOf(","), cut.lastIndexOf(" and "));
    formats = at > 20 ? cut.slice(0, at) : cut.slice(0, cut.lastIndexOf(" "));
  }
  return `${head}${formats}.${tail}`;
}

